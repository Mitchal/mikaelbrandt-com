// Renders page.html once per language and route from text/<lang>.json.
// Every page shares one template, so a layout change lands everywhere.
// Each language gets three routes on the same page: the fork, and the fork
// with track a or b already picked (so a link to an answer can be shared).
// Fails if a language is missing a key, has an extra one, or the template
// uses a key nobody defines, so the translations cannot drift apart.
//
//   node build.mjs          write the pages
//   node build.mjs --check  fail if the committed pages are out of date
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname } from "node:path";

const SITES = [
  { lang: "en", url: "https://mikaelbrandt.com/", dir: "", slugs: { a: "product", b: "integrations" } },
  { lang: "sv", url: "https://mikaelbrandt.se/", dir: "sv/", slugs: { a: "produkt", b: "integrationer" } },
];
const TRACKS = ["", "a", "b"]; // "" is the fork with nothing picked yet
const BUILT = ["lang", "track_attr", "alternates", "root", "home", "href_a", "href_b"];

const template = readFileSync("page.html", "utf8");
const used = new Set([...template.matchAll(/\{\{(\w+)\}\}/g)].map((m) => m[1]));
const translated = [...used].filter((k) => !BUILT.includes(k));

const up = (n) => "../".repeat(n);
const depth = (path) => path.split("/").filter(Boolean).length;
const slugOf = (site, track) => (track ? `${site.slugs[track]}/` : "");

function alternates(track) {
  return SITES.map((s) => `<link rel="alternate" hreflang="${s.lang}" href="${s.url}${slugOf(s, track)}">`).join("\n");
}

function render(site, text, track) {
  const pageUp = track ? 1 : 0;
  const values = {
    ...text,
    lang: site.lang,
    track_attr: track ? ` data-track="${track}"` : "",
    alternates: alternates(track),
    root: up(depth(site.dir) + pageUp),
    home: up(pageUp) || "./",
    href_a: up(pageUp) + slugOf(site, "a"),
    href_b: up(pageUp) + slugOf(site, "b"),
  };
  const note = `<!-- Generated by build.mjs from page.html and text/${site.lang}.json. Edit those, not this. -->`;
  const html = template.replace(/\{\{(\w+)\}\}/g, (_, k) => values[k]);
  return { out: `${site.dir}${slugOf(site, track)}index.html`, html: html.replace("<!doctype html>\n", `<!doctype html>\n${note}\n`) };
}

const problems = [];
const pages = SITES.flatMap((site) => {
  const text = JSON.parse(readFileSync(`text/${site.lang}.json`, "utf8"));
  for (const k of translated) if (!(k in text)) problems.push(`text/${site.lang}.json is missing "${k}"`);
  for (const k of Object.keys(text)) if (!used.has(k)) problems.push(`text/${site.lang}.json has unused "${k}"`);
  return TRACKS.map((track) => render(site, text, track));
});

if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

if (process.argv.includes("--check")) {
  const stale = pages.filter((p) => !existsSync(p.out) || readFileSync(p.out, "utf8") !== p.html);
  if (stale.length) {
    console.error(`Out of date, run node build.mjs: ${stale.map((p) => p.out).join(", ")}`);
    process.exit(1);
  }
  console.log("Pages are up to date.");
} else {
  for (const p of pages) {
    mkdirSync(dirname(p.out), { recursive: true });
    writeFileSync(p.out, p.html);
    console.log(`wrote ${p.out}`);
  }
}
